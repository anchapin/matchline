"""Gate #1159: pin the public API surface.

The public surface (docs/api.md) is a promise: symbols disappear, rename, or
change required signatures only with a deprecation notice. The snapshot in
tests/api_surface.json is generated by scripts/generate_api_surface.py; these
tests fail on drift and on silent public/internal churn.
"""

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "tests" / "api_surface.json"
GENERATOR = ROOT / "scripts" / "generate_api_surface.py"
SCHEMA = "matchline.api_surface/1"


def _gen():
    spec = importlib.util.spec_from_file_location("generate_api_surface", GENERATOR)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _snapshot() -> dict:
    return json.loads(SNAPSHOT.read_text())


def test_snapshot_schema_pinned():
    snap = _snapshot()
    assert snap["schema"] == SCHEMA
    assert set(snap) == {"schema", "modules", "packages"}


def test_surface_matches_snapshot():
    live = _gen().build()
    snap = _snapshot()
    if live != snap:
        drift = []
        for kind in ("modules", "packages"):
            for name in sorted(set(live[kind]) | set(snap[kind])):
                if live[kind].get(name) != snap[kind].get(name):
                    drift.append(name)
        raise AssertionError(
            "public API surface drifted from the pin in "
            f"{SNAPSHOT.relative_to(ROOT)} (drifted: {', '.join(drift)}). "
            "Per docs/api.md: removal or signature change needs a deprecation "
            "notice for one minor cycle; if the change is approved, run "
            "`python3 scripts/generate_api_surface.py` and commit the "
            "regenerated snapshot with the deprecation noted."
        )


def test_public_modules_importable():
    gen = _gen()
    for name in gen.PUBLIC_MODULES + gen.PUBLIC_PACKAGES:
        importlib.import_module(name)


def test_docs_page_implies_public():
    """A top-level module documented at docs/<module>.md must be declared public."""
    gen = _gen()
    declared = set(gen.PUBLIC_MODULES)
    docs_named = {p.stem for p in (ROOT / "docs").glob("*.md")}
    missing = sorted(m for m in docs_named if (ROOT / f"{m}.py").exists() and m not in declared)
    assert missing == [], (
        "modules with a module-named docs page but not declared public: "
        f"{missing}. Add them to PUBLIC_MODULES in "
        "scripts/generate_api_surface.py and regenerate the snapshot."
    )


def test_run_pipeline_is_public_and_documented():
    gen = _gen()
    assert "run_pipeline" in gen.PUBLIC_MODULES
    assert (ROOT / "docs" / "pipeline.md").exists()
