#!/usr/bin/env python3
"""Generate docs/repo-map.mmd, a Mermaid dependency map of the repo's own modules (#1096).

Scans the root-level modules and the synth package for internal imports with ast,
clusters them by name prefix, and writes a deterministic graph so CI can
drift-check it. Stdlib only; regenerate with:

    python scripts/generate_repo_map.py
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

# (cluster label, name prefixes that land in it). First match wins; anything
# else falls into CORE.
CLUSTERS: list[tuple[str, tuple[str, ...]]] = [
    (
        "BEM",
        (
            "bem.",
            "bem_",
            "materials",
            "constructions",
            "construction_library",
            "space_",
            "below_grade",
            "grade",
            "atria",
            "interstory",
            "daylight",
            "shading",
            "roof",
        ),
    ),
    ("IFC", ("ifc_", "ifc.")),
    ("HVAC", ("hvac_", "mech_", "legend_")),
    (
        "REVIEW",
        (
            "review_",
            "review.",
            "feedback_",
            "corrections",
            "diff",
            "export_package",
            "html_page",
            "convention_report",
        ),
    ),
    (
        "DETECTION",
        (
            "door_detect",
            "detection_provider",
            "facade_",
            "elevation_",
            "drawing_scale",
            "grid_detect",
            "symbols",
        ),
    ),
    (
        "PLAN",
        (
            "pdf_",
            "sheet_",
            "registration",
            "link",
            "room_labels",
            "plan_walls",
            "opening_",
            "matchlines",
            "polygon_classify",
        ),
    ),
]
DEFAULT_CLUSTER = "CORE"


def cluster_of(module: str) -> str:
    for label, prefixes in CLUSTERS:
        for p in prefixes:
            if module == p or module.startswith(p):
                return label
    return DEFAULT_CLUSTER


def internal_modules(root: Path) -> set[str]:
    names = {p.stem for p in root.glob("*.py")}
    for pkg in ("synth", "bem", "ifc", "review"):
        pkg_dir = root / pkg
        if pkg_dir.is_dir():
            names.add(pkg)
            for p in pkg_dir.glob("*.py"):
                if p.stem != "__init__":
                    names.add(f"{pkg}.{p.stem}")
    return names


def imports_of(path: Path, pkg: str | None) -> set[str]:
    """Internal module names imported by one file. pkg is 'synth' inside the package."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                found.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level and pkg:
                # Relative import inside synth: from . import x / from .x import y
                if node.module:
                    found.add(f"{pkg}.{node.module.split('.')[0]}")
                else:
                    for alias in node.names:
                        found.add(f"{pkg}.{alias.name}")
            elif node.module:
                found.add(node.module)
    return found


def build(root: Path) -> tuple[list[str], list[tuple[str, str]], dict[str, str]]:
    mods = internal_modules(root)
    edges: set[tuple[str, str]] = set()

    def add_edge(src: str, imp: str) -> None:
        target = imp if imp in mods else imp.split(".")[0]
        if target in mods and target != src:
            edges.add((src, target))

    for path in sorted(root.glob("*.py")):
        src = path.stem
        for imp in imports_of(path, None):
            add_edge(src, imp)
    for pkg in ("synth", "bem", "ifc", "review"):
        pkg_dir = root / pkg
        if pkg_dir.is_dir():
            for path in sorted(pkg_dir.glob("*.py")):
                if path.stem == "__init__":
                    continue
                src = f"{pkg}.{path.stem}"
                for imp in imports_of(path, pkg):
                    add_edge(src, imp)

    def node_id(name: str) -> str:
        return name.replace(".", "_")

    cluster_map = {m: cluster_of(m) for m in sorted(mods)}
    nodes: list[str] = []
    for label, _ in CLUSTERS + [(DEFAULT_CLUSTER, ())]:
        members = [m for m, c in cluster_map.items() if c == label]
        if not members:
            continue
        nodes.append(f"  subgraph {label}")
        for m in members:
            nodes.append(f"    {node_id(m)}")
        nodes.append("  end")
    edge_lines = [(node_id(a), node_id(b)) for a, b in sorted(edges)]
    return nodes, edge_lines, cluster_map


def render(nodes: list[str], edges: list[tuple[str, str]]) -> str:
    lines = [
        "%% Generated by scripts/generate_repo_map.py; do not edit by hand.",
        "%% Regenerate with: python scripts/generate_repo_map.py",
        "graph LR",
    ]
    lines.extend(nodes)
    for a, b in edges:
        lines.append(f"  {a} --> {b}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repo root (default: two levels up from this script)",
    )
    ap.add_argument(
        "--out", type=Path, default=None, help="output path (default: <root>/docs/repo-map.mmd)"
    )
    args = ap.parse_args()
    out = args.out or (args.root / "docs" / "repo-map.mmd")
    nodes, edges, cluster_map = build(args.root)
    counts: dict[str, int] = {}
    for c in cluster_map.values():
        counts[c] = counts.get(c, 0) + 1
    out.parent.mkdir(parents=True, exist_ok=True)
    graph = render(nodes, edges)
    out.write_text(graph, encoding="utf-8")
    # A .mmd blob shows as code on GitHub; a fenced block in a .md page renders
    # with pan/zoom, so write the wrapper beside the source of truth.
    md = out.with_suffix(".md")
    md.write_text(
        "# Repo map\n\n"
        "Auto-generated Mermaid map of the repo's own module dependencies, built\n"
        "from import statements by `scripts/generate_repo_map.py`. Do not edit by\n"
        "hand; regenerate with `python scripts/generate_repo_map.py`. The graph is\n"
        "fenced below so it renders (pan/zoom) on GitHub.\n\n"
        "```mermaid\n" + graph + "```\n",
        encoding="utf-8",
    )
    print(f"{len(cluster_map)} modules, {len(edges)} edges -> {out} (+ {md.name})")
    print("  " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()
