"""Space-use defaults (#685): fill missing loads and schedules per room.

Source: DOE Commercial Prototype Building Models, ASHRAE 90.1-2019 edition,
as encoded in NREL openstudio-standards (see ``space_use_defaults_data``,
generated by ``scripts/build_space_use_defaults.py``).

``apply_space_use_defaults(model)`` gives every room a ``space_type`` from
its name, then fills lighting power density, occupant density, equipment
power density and the three schedules ONLY where the model has no value of
its own. A drawing-derived value (for example an LPD from a lighting
schedule takeoff) is never overwritten. Each filled value carries a
Provenance whose method is ``"doe_prototype_default"`` and whose note names
the edition and the source row, so every number traces to one table row.

Shafts and elevator cores get no loads. Rooms whose name matches no rule
get the large-office whole-building average at lower confidence and are
listed in the returned summary for review.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import List, Optional, Tuple

from building_model import Provenance, SpaceLighting, SpaceUse
from space_use_defaults_data import (
    EDITION,
    SCHEDULES,
    SOURCE,
    SOURCE_VERSION,
    SPACE_USE_DEFAULTS,
)

METHOD = "doe_prototype_default"
FALLBACK_TYPE = "office_whole_building"
MATCH_CONFIDENCE = 0.7  # room name matched a rule
FALLBACK_CONFIDENCE = 0.4  # no rule matched; whole-building average
NO_LOAD_POLY_TYPES = ("shaft", "elevator_core")

# (pattern, space_type), first match wins; matched against the upper-cased
# room name with punctuation turned into spaces. Order matters: specific
# names before generic ones ("ELEVATOR LOBBY" before "LOBBY", "IT" rooms
# before "OFFICE").
_RULES: List[Tuple[str, str]] = [
    (r"\bDATA ?(CENTER|CENTRE)\b|\bSERVER\b", "data_center"),
    (
        r"\bIT\b|\bIDF\b|\bMDF\b|\bTELECOM\b|\bTEL(E)? ?DATA\b|\bCOMM(S|UNICATIONS)? ROOM\b",
        "it_room",
    ),
    (
        r"\b(ELEC|ELECT|ELECTRICAL|MECH|MECHANICAL|BOILER|PUMP|FAN|RISER|JANITOR|JAN|CUSTODIAL|UTILITY)\b",
        "mechanical_electrical",
    ),
    (r"\bELEV(ATOR)? LOBBY\b", "elevator_lobby"),
    (r"\b(LOBBY|RECEPTION|VESTIBULE|ENTRY|FOYER|WAITING)\b", "lobby"),
    (r"\b(CONF|CONFERENCE|MEETING|BOARD ?ROOM|HUDDLE|TRAINING)\b", "conference"),
    (r"\b(BREAK|PANTRY|LOUNGE|COFFEE|WORK ?ROOM)\b", "break_room"),
    (r"\b(KITCHEN|SERVERY)\b", "kitchen"),
    (r"\b(DINING|CAFE|CAFETERIA|CANTEEN)\b", "dining"),
    (r"\b(PRINT|COPY|MAIL)\b", "print_room"),
    (r"\bVENDING\b", "vending"),
    (r"\b(TOILET|RESTROOM|WC|LAV|LAVATORY|MEN|WOMEN|MENS|WOMENS|SHOWER|LOCKER)\b", "restroom"),
    (r"\b(STAIR|STAIRS|STAIRWELL|STAIRWAY)\b", "stair"),
    (r"\b(CORR|CORRIDOR|HALL|HALLWAY|PASSAGE)\b", "corridor"),
    (r"\b(STOR|STORAGE|STORE ?ROOM|FILE|FILES|ARCHIVE|CLOSET|CLO)\b", "storage"),
    (r"\b(CLASSROOM|CLASS|SEMINAR)\b", "classroom"),
    (r"\b(LIBRARY|READING)\b", "library"),
    (r"\b(GYM|GYMNASIUM|FITNESS|EXERCISE)\b", "gym"),
    (r"\b(AUDITORIUM|THEATER|THEATRE|ASSEMBLY)\b", "auditorium"),
    (r"\b(RETAIL|SHOP|SALES)\b", "retail"),
    (r"\b(WAREHOUSE|LOADING)\b", "warehouse"),
    (r"\b(OPEN OFFICE|OPEN PLAN|WORKSTATIONS?|BULLPEN|OPEN AREA)\b", "open_office"),
    (r"\b(OFFICE|OFF|OFC|PRIVATE|MANAGER|DIRECTOR|EXEC|EXECUTIVE)\b", "closed_office"),
]
_COMPILED = [(re.compile(p), t) for p, t in _RULES]


@dataclass
class SpaceUseSummary:
    """What apply_space_use_defaults did, for logs and review."""

    typed: int = 0  # spaces given a space_type
    filled: dict = field(default_factory=dict)  # field -> count filled from defaults
    kept: dict = field(default_factory=dict)  # field -> count kept (model had a value)
    fallback: List[str] = field(default_factory=list)  # space ids on the whole-building row
    skipped: List[str] = field(default_factory=list)  # shafts / elevator cores


def classify_space_type(name: str, poly_type: str = "room") -> Tuple[Optional[str], float]:
    """Room name -> (space_type key, confidence); (None, 0) for no-load spaces."""
    if poly_type in NO_LOAD_POLY_TYPES:
        return None, 0.0
    if poly_type == "closet":
        return "storage", MATCH_CONFIDENCE
    text = " " + re.sub(r"[^A-Z0-9]+", " ", (name or "").upper()) + " "
    for rx, key in _COMPILED:
        if rx.search(text):
            return key, MATCH_CONFIDENCE
    return FALLBACK_TYPE, FALLBACK_CONFIDENCE


def _prov(space_type: str, field_name: str, confidence: float) -> Provenance:
    row = SPACE_USE_DEFAULTS[space_type]
    return Provenance(
        sheet_id="space_use_defaults",
        revision=0,
        method=METHOD,
        confidence=confidence,
        note=(
            f"{SOURCE}, {EDITION} ({SOURCE_VERSION}); row "
            f"{row['source_building_type']} / {row['source_space_type']}; {field_name}"
        ),
    )


def _count(d: dict, k: str) -> None:
    d[k] = d.get(k, 0) + 1


def apply_space_use_defaults(model) -> SpaceUseSummary:
    """Fill missing per-space loads and schedules in place; never overwrite."""
    summary = SpaceUseSummary()
    for sid in sorted(model.spaces):
        sp = model.spaces[sid]
        if sp.use is None:
            sp.use = SpaceUse()
        if sp.lighting is None:
            sp.lighting = SpaceLighting()
        use = sp.use
        st = use.space_type
        conf = MATCH_CONFIDENCE
        if not st:
            st, conf = classify_space_type(sp.name, getattr(sp, "poly_type", "room"))
            if st is None:
                summary.skipped.append(sid)
                continue
            use.space_type = st
            summary.typed += 1
        if st not in SPACE_USE_DEFAULTS:
            raise ValueError(f"{sid}: unknown space_type {st!r}")
        if st == FALLBACK_TYPE:
            conf = FALLBACK_CONFIDENCE
            summary.fallback.append(sid)
        row = SPACE_USE_DEFAULTS[st]
        filled_any = []

        # lighting: a drawing-derived LPD (or fixture watts) wins
        has_lpd = sp.lighting.lpd_w_m2 is not None or sp.lighting.lpd_w_ft2 is not None
        has_lpd = has_lpd or (sp.lighting.total_w or 0.0) > 0
        if has_lpd:
            _count(summary.kept, "lpd_w_m2")
        elif row["lpd_w_m2"] is not None:
            sp.lighting.lpd_w_m2 = row["lpd_w_m2"]
            sp.lighting.lpd_w_ft2 = row["lighting_w_ft2"]
            sp.lighting.provenance = _prov(st, "lighting_per_area", conf)
            _count(summary.filled, "lpd_w_m2")

        for attr, key in (
            ("people_per_m2", "people_per_m2"),
            ("equipment_w_m2", "equipment_w_m2"),
            ("activity_w_per_person", "activity_w_per_person"),
        ):
            if getattr(use, attr) is not None:
                _count(summary.kept, attr)
            elif row[key] is not None:
                setattr(use, attr, row[key])
                filled_any.append(attr)
                _count(summary.filled, attr)
        for attr in ("lighting_schedule", "occupancy_schedule", "equipment_schedule"):
            if getattr(use, attr):
                _count(summary.kept, attr)
            elif row[attr]:
                setattr(use, attr, row[attr])
                filled_any.append(attr)
                _count(summary.filled, attr)
        if filled_any and use.provenance is None:
            use.provenance = _prov(st, ", ".join(filled_any), conf)
    return summary


def schedule_profile(name: str) -> dict:
    """Hourly fractions for a schedule: {weekday, saturday, sunday_holiday}."""
    try:
        return SCHEDULES[name]
    except KeyError:
        raise KeyError(f"no schedule {name!r} in space_use_defaults_data.SCHEDULES") from None


def lighting_watts(space) -> float:
    """Fixture watts when counted, else LPD x area (0 when neither is known)."""
    lt = space.lighting or SpaceLighting()
    if (lt.total_w or 0.0) > 0:
        return lt.total_w
    lpd = lt.lpd_w_m2
    if lpd is None and lt.lpd_w_ft2 is not None:
        lpd = lt.lpd_w_ft2 * 10.7639
    return (lpd or 0.0) * (space.area_m2 or 0.0)
